const listeners = new Set();

export function getLang() {
  try { return localStorage.getItem("carzen_lang") === "en" ? "en" : "ar"; }
  catch { return "ar"; }
}

export function applyLang(lang = getLang()) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function setLang(lang) {
  localStorage.setItem("carzen_lang", lang === "en" ? "en" : "ar");
  applyLang(lang);
  listeners.forEach((fn) => fn(getLang()));
  window.dispatchEvent(new CustomEvent("carzen-lang"));
}

export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars) {
  const lang = getLang();
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function L(value) {
  if (value && typeof value === "object" && ("ar" in value || "en" in value)) {
    const lang = getLang();
    return value[lang] || value.ar || value.en || "";
  }
  return value ?? "";
}

export function staffStatus(status) {
  const map = {
    pending: ["بانتظار التأكيد", "Pending"],
    confirmed: ["مؤكد", "Confirmed"],
    waiting: ["في الانتظار", "Waiting"],
    in_service: ["جارٍ التنفيذ", "In service"],
    completed: ["مكتمل", "Completed"],
    cancelled: ["ملغي", "Cancelled"],
    no_show: ["لم يحضر", "No show"],
  };
  const pair = map[status] || [status, status];
  return getLang() === "ar" ? pair[0] : pair[1];
}
