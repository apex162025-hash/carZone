// ── SQL literal helpers ──────────────────────────────────────────────────────

class Raw {
  readonly sql: string;
  constructor(sql: string) {
    this.sql = sql;
  }
}
const raw = (sql: string) => new Raw(sql);
const json = (v: unknown) => (v === null || v === undefined ? null : raw(`${str(JSON.stringify(v))}::jsonb`));
const textArr = (a: string[]) => raw(a.length ? `array[${a.map(str).join(", ")}]::text[]` : `'{}'::text[]`);
const smallintArr = (a: number[]) => raw(`array[${a.join(", ")}]::smallint[]`);

function str(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (v instanceof Raw) return v.sql;
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`Non-finite number in seed: ${v}`);
    return String(v);
  }
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "string") return str(v);
  throw new Error(`Unsupported literal: ${JSON.stringify(v)}`);
}

const out: string[] = [];

function insert(table: string, rows: Row[], chunk = 400) {
  if (!rows.length) return;
  const cols = Object.keys(rows[0]);
  out.push(`-- ${table}: ${rows.length} rows`);
  for (let i = 0; i < rows.length; i += chunk) {
    const values = rows
      .slice(i, i + chunk)
      .map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`)
      .join(",\n");
    out.push(`insert into public.${table} (${cols.join(", ")}) values\n${values};`);
  }
  out.push("");
}

